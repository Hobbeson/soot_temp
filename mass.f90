CONTAINS

SUBROUTINE ENSURE_WALL(NW)
  INTEGER, INTENT(IN) :: NW
  IF (ARRAYS_ALLOCATED .AND. NW == PREV_NW) RETURN
  IF (ALLOCATED(WALL_BC_TYPE_TMP)) DEALLOCATE(WALL_BC_TYPE_TMP, WALL_B1_INDEX_TMP,&
    BC_IIG_TMP, BC_JJG_TMP, BC_KKG_TMP, BC_IOR_TMP, BC_II_TMP, BC_JJ_TMP, BC_KK_TMP,&
    BP1_RHO_F_TMP, BP1_ZZ_F_TMP,&
    EWC_BOUNDARY_TYPE_PREVIOUS_TMP, UVW_SAVE_TMP)
  ALLOCATE(WALL_BC_TYPE_TMP(NW), WALL_B1_INDEX_TMP(NW),&
    BC_IIG_TMP(NW), BC_JJG_TMP(NW), BC_KKG_TMP(NW), BC_IOR_TMP(NW),&
    BC_II_TMP(NW), BC_JJ_TMP(NW), BC_KK_TMP(NW),&
    BP1_RHO_F_TMP(NW), BP1_ZZ_F_TMP(NW * N_TRACKED_SPECIES),&
    EWC_BOUNDARY_TYPE_PREVIOUS_TMP(NW), UVW_SAVE_TMP(NW))
  PREV_NW = NW
END SUBROUTINE ENSURE_WALL

SUBROUTINE ENSURE_SPECIES(NTS)
  INTEGER, INTENT(IN) :: NTS
  IF (ARRAYS_ALLOCATED .AND. NTS == PREV_NTS) RETURN
  IF (ALLOCATED(SM_MW_TMP)) DEALLOCATE(SM_MW_TMP, SM_DEPOSITING_TMP)
  ALLOCATE(SM_MW_TMP(NTS), SM_DEPOSITING_TMP(NTS))
  PREV_NTS = NTS
END SUBROUTINE ENSURE_SPECIES

SUBROUTINE ENSURE_CELL(NC)
  INTEGER, INTENT(IN) :: NC
  IF (ARRAYS_ALLOCATED .AND. NC == PREV_NC) RETURN
  IF (ALLOCATED(CELL_SOLID_TMP)) DEALLOCATE(CELL_SOLID_TMP, CELL_WALL_INDEX_TMP, CELL_EXTERIOR_TMP)
  ALLOCATE(CELL_SOLID_TMP(NC), CELL_WALL_INDEX_TMP(NC*7), CELL_EXTERIOR_TMP(NC))
  PREV_NC = NC
END SUBROUTINE ENSURE_CELL

SUBROUTINE PACK_MP_C(mp)
  TYPE(MASS_MP_C), INTENT(INOUT) :: mp
  INTEGER :: I,J,K,IW,II,JJ,KK,IC,NTS,NW,NC,NSPEC
  TYPE(WALL_TYPE), POINTER :: WC
  TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
  TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1
  TYPE(EXTERNAL_WALL_TYPE), POINTER :: EWC

  NTS = N_TRACKED_SPECIES
  NW  = N_EXTERNAL_WALL_CELLS + N_INTERNAL_WALL_CELLS
  NC  = (IBAR+1)*(JBAR+1)*(KBAR+1)


  mp%U  = C_LOC(U(LBOUND(U,1),LBOUND(U,2),LBOUND(U,3)))
  mp%V  = C_LOC(V(LBOUND(V,1),LBOUND(V,2),LBOUND(V,3)))
  mp%W  = C_LOC(W(LBOUND(W,1),LBOUND(W,2),LBOUND(W,3)))
  mp%US = C_LOC(US(LBOUND(US,1),LBOUND(US,2),LBOUND(US,3)))
  mp%VS = C_LOC(VS(LBOUND(VS,1),LBOUND(VS,2),LBOUND(VS,3)))
  mp%WS = C_LOC(WS(LBOUND(WS,1),LBOUND(WS,2),LBOUND(WS,3)))
  mp%RHO  = C_LOC(RHO(LBOUND(RHO,1),LBOUND(RHO,2),LBOUND(RHO,3)))
  mp%RHOS = C_LOC(RHOS(LBOUND(RHOS,1),LBOUND(RHOS,2),LBOUND(RHOS,3)))
  mp%TMP  = C_LOC(TMP(LBOUND(TMP,1),LBOUND(TMP,2),LBOUND(TMP,3)))
  mp%RSUM = C_LOC(RSUM(LBOUND(RSUM,1),LBOUND(RSUM,2),LBOUND(RSUM,3)))
  mp%MU   = C_LOC(MU(LBOUND(MU,1),LBOUND(MU,2),LBOUND(MU,3)))
  mp%Q    = C_LOC(Q(LBOUND(Q,1),LBOUND(Q,2),LBOUND(Q,3)))
  mp%D_SOURCE = C_LOC(D_SOURCE(LBOUND(D_SOURCE,1),LBOUND(D_SOURCE,2),LBOUND(D_SOURCE,3)))


  mp%ZZ  = C_LOC(ZZ(LBOUND(ZZ,1),LBOUND(ZZ,2),LBOUND(ZZ,3),LBOUND(ZZ,4)))
  mp%ZZS = C_LOC(ZZS(LBOUND(ZZS,1),LBOUND(ZZS,2),LBOUND(ZZS,3),LBOUND(ZZS,4)))
  mp%DEL_RHO_D_DEL_Z = C_LOC(DEL_RHO_D_DEL_Z(LBOUND(DEL_RHO_D_DEL_Z,1),LBOUND(DEL_RHO_D_DEL_Z,2),&
    LBOUND(DEL_RHO_D_DEL_Z,3),LBOUND(DEL_RHO_D_DEL_Z,4)))
  mp%FX = C_LOC(FX(LBOUND(FX,1),LBOUND(FX,2),LBOUND(FX,3),LBOUND(FX,4)))
  mp%FY = C_LOC(FY(LBOUND(FY,1),LBOUND(FY,2),LBOUND(FY,3),LBOUND(FY,4)))
  mp%FZ = C_LOC(FZ(LBOUND(FZ,1),LBOUND(FZ,2),LBOUND(FZ,3),LBOUND(FZ,4)))
  mp%M_DOT_PPP = C_LOC(M_DOT_PPP(LBOUND(M_DOT_PPP,1),LBOUND(M_DOT_PPP,2),&
    LBOUND(M_DOT_PPP,3),LBOUND(M_DOT_PPP,4)))
  mp%ADV_FX = C_LOC(ADV_FX(LBOUND(ADV_FX,1),LBOUND(ADV_FX,2),LBOUND(ADV_FX,3),LBOUND(ADV_FX,4)))
  mp%ADV_FY = C_LOC(ADV_FY(LBOUND(ADV_FY,1),LBOUND(ADV_FY,2),LBOUND(ADV_FY,3),LBOUND(ADV_FY,4)))
  mp%ADV_FZ = C_LOC(ADV_FZ(LBOUND(ADV_FZ,1),LBOUND(ADV_FZ,2),LBOUND(ADV_FZ,3),LBOUND(ADV_FZ,4)))


  mp%R    = C_LOC(R(LBOUND(R,1)))
  mp%RC   = C_LOC(RC(LBOUND(RC,1)))
  mp%RRN  = C_LOC(RRN(LBOUND(RRN,1)))
  mp%DX   = C_LOC(DX(LBOUND(DX,1)))
  mp%RDX  = C_LOC(RDX(LBOUND(RDX,1)))
  mp%RDXN = C_LOC(RDXN(LBOUND(RDXN,1)))
  mp%DY   = C_LOC(DY(LBOUND(DY,1)))
  mp%RDY  = C_LOC(RDY(LBOUND(RDY,1)))
  mp%DYN  = C_LOC(DYN(LBOUND(DYN,1)))
  mp%RDYN = C_LOC(RDYN(LBOUND(RDYN,1)))
  mp%DZ   = C_LOC(DZ(LBOUND(DZ,1)))
  mp%RDZ  = C_LOC(RDZ(LBOUND(RDZ,1)))
  mp%DZN  = C_LOC(DZN(LBOUND(DZN,1)))
  mp%RDZN = C_LOC(RDZN(LBOUND(RDZN,1)))
  mp%XC   = C_LOC(XC(LBOUND(XC,1)))
  mp%ZC   = C_LOC(ZC(LBOUND(ZC,1)))


  mp%WORK1 = C_LOC(WORK1(LBOUND(WORK1,1),LBOUND(WORK1,2),LBOUND(WORK1,3)))
  mp%WORK2 = C_LOC(WORK2(LBOUND(WORK2,1),LBOUND(WORK2,2),LBOUND(WORK2,3)))
  mp%WORK3 = C_LOC(WORK3(LBOUND(WORK3,1),LBOUND(WORK3,2),LBOUND(WORK3,3)))
  mp%WORK4 = C_LOC(WORK4(LBOUND(WORK4,1),LBOUND(WORK4,2),LBOUND(WORK4,3)))
  mp%WORK5 = C_LOC(WORK5(LBOUND(WORK5,1),LBOUND(WORK5,2),LBOUND(WORK5,3)))
  mp%SWORK4= C_LOC(SWORK4(LBOUND(SWORK4,1),LBOUND(SWORK4,2),LBOUND(SWORK4,3),LBOUND(SWORK4,4)))

  mp%PBAR = C_LOC(PBAR(LBOUND(PBAR,1),LBOUND(PBAR,2)))
  mp%PBAR_S = C_LOC(PBAR_S(LBOUND(PBAR_S,1),LBOUND(PBAR_S,2)))
  mp%PRESSURE_ZONE = C_LOC(PRESSURE_ZONE(LBOUND(PRESSURE_ZONE,1),LBOUND(PRESSURE_ZONE,2),&
    LBOUND(PRESSURE_ZONE,3)))
  mp%D_PBAR_DT  = C_LOC(D_PBAR_DT(1))
  mp%D_PBAR_DT_S = C_LOC(D_PBAR_DT_S(1))


