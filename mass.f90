    BC_JJG_TMP(IW) = BC%JJG
    BC_KKG_TMP(IW) = BC%KKG
    BC_IOR_TMP(IW) = BC%IOR
    BC_II_TMP(IW) = BC%II
    BC_JJ_TMP(IW) = BC%JJ
    BC_KK_TMP(IW) = BC%KK
    BP1_RHO_F_TMP(IW) = B1%RHO_F
    BP1_ZZ_F_TMP((IW-1)*NTS+1 : IW*NTS) = B1%ZZ_F(1:NTS)
  ENDDO
  mp%WALL_BC_TYPE = C_LOC(WALL_BC_TYPE_TMP(1))
  mp%WALL_B1_INDEX = C_LOC(WALL_B1_INDEX_TMP(1))
  mp%BC_IIG = C_LOC(BC_IIG_TMP(1))
  mp%BC_JJG = C_LOC(BC_JJG_TMP(1))
  mp%BC_KKG = C_LOC(BC_KKG_TMP(1))
  mp%BC_IOR = C_LOC(BC_IOR_TMP(1))
  mp%BC_II = C_LOC(BC_II_TMP(1))
  mp%BC_JJ = C_LOC(BC_JJ_TMP(1))
  mp%BC_KK = C_LOC(BC_KK_TMP(1))
  mp%BP1_RHO_F = C_LOC(BP1_RHO_F_TMP(1))
  mp%BP1_ZZ_F = C_LOC(BP1_ZZ_F_TMP(1))

  ! EXTERNAL_WALL
  DO IW = 1, N_EXTERNAL_WALL_CELLS
    EWC => EXTERNAL_WALL(IW)
    EWC_BOUNDARY_TYPE_PREVIOUS_TMP(IW) = EWC%BOUNDARY_TYPE_PREVIOUS
  ENDDO
  mp%EWC_BOUNDARY_TYPE_PREVIOUS = C_LOC(EWC_BOUNDARY_TYPE_PREVIOUS_TMP(1))


  CALL ENSURE_SPECIES(NTS)
  DO I = 1, NTS
    SM_MW_TMP(I) = SPECIES_MIXTURE(I)%MW
    SM_DEPOSITING_TMP(I) = MERGE(1.0_EB, 0.0_EB, SPECIES_MIXTURE(I)%DEPOSITING)
  ENDDO
  mp%SM_MW = C_LOC(SM_MW_TMP(1))
  mp%SM_DEPOSITING = C_LOC(SM_DEPOSITING_TMP(1))


  mp%IBAR = IBAR; mp%JBAR = JBAR; mp%KBAR = KBAR
  mp%IBP1 = IBAR+1; mp%JBP1 = JBAR+1; mp%KBP1 = KBAR+1
  mp%N_EXTERNAL_WALL_CELLS = N_EXTERNAL_WALL_CELLS
  mp%N_INTERNAL_WALL_CELLS = N_INTERNAL_WALL_CELLS
  mp%N_ZONE = N_ZONE
  mp%N_TOTAL_SCALARS = N_TOTAL_SCALARS
  mp%N_TRACKED_SPECIES = N_TRACKED_SPECIES
  mp%N_PASSIVE_SCALARS = N_PASSIVE_SCALARS
  mp%ZETA_INDEX = ZETA_INDEX
  mp%PREDICTOR_FLAG = MERGE(1, 0, PREDICTOR)
  mp%FIRST_PASS_FLAG = MERGE(1, 0, FIRST_PASS)
  mp%CC_IBM_FLAG = MERGE(1, 0, CC_IBM)
  mp%STORE_SPECIES_FLUX_FLAG = MERGE(1, 0, STORE_SPECIES_FLUX)
  mp%I_FLUX_LIMITER = I_FLUX_LIMITER
  mp%FLUX_LIMITER_MW_CORRECTION_FLAG = MERGE(1, 0, FLUX_LIMITER_MW_CORRECTION)
  mp%PERIODIC_TEST_VAL = PERIODIC_TEST
  mp%ICYC_VAL = ICYC
  mp%SOLID_PHASE_ONLY_FLAG = MERGE(1, 0, SOLID_PHASE_ONLY)
  mp%GRAVITATIONAL_SETTLING_FLAG = MERGE(1, 0, GRAVITATIONAL_SETTLING)
  mp%THERMOPHORETIC_SETTLING_FLAG = MERGE(1, 0, THERMOPHORETIC_SETTLING)
  mp%RHOMIN_VAL = REAL(RHOMIN, C_DOUBLE)
  mp%RHOMAX_VAL = REAL(RHOMAX, C_DOUBLE)
  mp%SP_DENSITY_SOLID = C_NULL_PTR
END SUBROUTINE PACK_MP_C


SUBROUTINE MASS_FINITE_DIFFERENCES(NM)
  INTEGER, INTENT(IN) :: NM
  TYPE(MASS_MP_C) :: mp
  REAL(EB) :: TNOW

  IF (SOLID_PHASE_ONLY) RETURN
  TNOW = CURRENT_TIME()
  CALL POINT_TO_MESH(NM)
  IF (PREDICTOR) DT_RESTRICT_COUNT = 0

  CALL PACK_MP_C(mp)
  CALL mass_c_finite_differences(mp)

  T_USED(3) = T_USED(3) + CURRENT_TIME() - TNOW
END SUBROUTINE MASS_FINITE_DIFFERENCES


SUBROUTINE DENSITY(T, DT, NM)
  USE SOOT_ROUTINES, ONLY: SETTLING_VELOCITY
  USE CC_SCALARS, ONLY: SET_EXIMADVFLX_3D, ROTATED_CUBE_RHS_ZZ
  USE MANUFACTURED_SOLUTIONS, ONLY: VD2D_MMS_Z_SRC, UF_MMS, WF_MMS
  INTEGER, INTENT(IN) :: NM
  REAL(EB), INTENT(IN) :: T, DT
  TYPE(MASS_MP_C) :: mp
  REAL(EB) :: TNOW

  IF (SOLID_PHASE_ONLY) RETURN
  SELECT CASE (PERIODIC_TEST)
    CASE DEFAULT
      IF (ICYC <= 1) RETURN
    CASE (5, 8)
      RETURN
    CASE (4, 7, 11, 21, 22)
  END SELECT
  TNOW = CURRENT_TIME()
  CALL POINT_TO_MESH(NM)

  ! FIRST_PASS 时调用 SETTLING_VELOCITY (PREDICTOR 步)
  IF (PREDICTOR .AND. FIRST_PASS) THEN
    IF (ANY(SPECIES_MIXTURE%DEPOSITING) .AND. &
        (GRAVITATIONAL_SETTLING .OR. THERMOPHORETIC_SETTLING)) CALL SETTLING_VELOCITY(NM)
  ENDIF

  ! CORRECTOR 步的 SETTLING_VELOCITY
  IF (.NOT. PREDICTOR) THEN
    IF (ANY(SPECIES_MIXTURE%DEPOSITING) .AND. &
        (GRAVITATIONAL_SETTLING .OR. THERMOPHORETIC_SETTLING)) CALL SETTLING_VELOCITY(NM)
  ENDIF

  CALL PACK_MP_C(mp)
  CALL mass_c_density(REAL(T, C_DOUBLE), REAL(DT, C_DOUBLE), mp)

  ! 后处理: CC_IBM
  IF (CC_IBM) THEN
    IF (PREDICTOR) THEN
      CALL SET_EXIMADVFLX_3D(NM, WORK1, WORK2, WORK3)
    ELSE
      CALL SET_EXIMADVFLX_3D(NM, WORK1, WORK2, WORK3)
    ENDIF
  ENDIF

  T_USED(3) = T_USED(3) + CURRENT_TIME() - TNOW
END SUBROUTINE DENSITY


SUBROUTINE fds_get_scalar_face_value(uu_ptr, scalar_ptr, face_ptr, &
    ilo, ihi, jlo, jhi, klo, khi, dir, i_flux_limiter, &
    ni, nj, nk) BIND(C, NAME="fds_get_scalar_face_value")
  USE ISO_C_BINDING, ONLY: C_DOUBLE, C_INT, C_PTR
  USE MATH_FUNCTIONS, ONLY: GET_SCALAR_FACE_VALUE
  IMPLICIT NONE
  TYPE(C_PTR), INTENT(IN), VALUE :: uu_ptr, scalar_ptr, face_ptr
  INTEGER(C_INT), INTENT(IN), VALUE :: ilo, ihi, jlo, jhi, klo, khi, dir, &
                                        i_flux_limiter, ni, nj, nk
  REAL(EB), POINTER, DIMENSION(:,:,:) :: uu, scalar, face
  CALL C_F_POINTER(uu_ptr, uu, [ni, nj, nk])
