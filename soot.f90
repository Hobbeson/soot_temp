  mp%GVEC_X = GVEC(1); mp%GVEC_Y = GVEC(2); mp%GVEC_Z = GVEC(3)
  mp%NULL_BOUNDARY_VAL = NULL_BOUNDARY
  mp%OPEN_BOUNDARY_VAL = OPEN_BOUNDARY
  mp%INTERPOLATED_BOUNDARY_VAL = INTERPOLATED_BOUNDARY
  NA = N_AGGLOMERATION_SPECIES
  mp%N_AGGLOMERATION_SPECIES = NA
  mp%SOOT_INDEX = SOOT_INDEX; mp%O2_INDEX = O2_INDEX
  mp%N_SURFACE_DENSITY_SPECIES = N_SURFACE_DENSITY_SPECIES
  mp%R0_VAL = R0; mp%MW_O2_VAL = MW_O2
  mp%ZZ_MIN_GLOBAL_VAL = ZZ_MIN_GLOBAL

  IF (ALLOCATED(NU_SOOT_OX_TMP)) DEALLOCATE(NU_SOOT_OX_TMP)
  ALLOCATE(NU_SOOT_OX_TMP(NTS))
  NU_SOOT_OX_TMP(1:NTS) = NU_SOOT_OX(1:NTS)
  mp%NU_SOOT_OX = C_LOC(NU_SOOT_OX_TMP(1))
  mp%I_MAX_TEMP_VAL = I_MAX_TEMP
  mp%N_TOTAL_SCALARS_VAL = N_TRACKED_SPECIES

  CALL FILL_SM_ARRAYS(NTS)
  mp%SM_DEPOSITING          = C_LOC(SM_DEPOSITING_TMP(1))
  mp%SM_MEAN_DIAMETER       = C_LOC(SM_MEAN_DIAMETER_TMP(1))
  mp%SM_DENSITY_SOLID       = C_LOC(SM_DENSITY_SOLID_TMP(1))
  mp%SM_THERMOPHORETIC_DIAMETER = C_LOC(SM_THERMOPHORETIC_DIAMETER_TMP(1))
  mp%SM_CONDUCTIVITY_SOLID  = C_LOC(SM_CONDUCTIVITY_SOLID_TMP(1))
  mp%SM_H_F                 = C_LOC(SM_H_F_TMP(1))
  mp%SM_RCON                = C_LOC(SM_RCON_TMP(1))
  mp%SM_MW                  = C_LOC(SM_MW_TMP(1))
  mp%SM_AWM_INDEX           = C_LOC(SM_AWM_INDEX_TMP(1))
  mp%SM_AGGLOMERATION_INDEX = C_LOC(SM_AGGLOMERATION_INDEX_TMP(1))

  NSPEC = SIZE(SPECIES)
  CALL FILL_SP_ARRAYS(NSPEC)
  mp%SP_DENSITY_SOLID      = C_LOC(SP_DENSITY_SOLID_TMP(1))
  mp%SP_CONDUCTIVITY_SOLID = C_LOC(SP_CONDUCTIVITY_SOLID_TMP(1))
  mp%SP_AWM_INDEX          = C_LOC(SP_AWM_INDEX_TMP(1))
  mp%SP_AGGLOMERATING      = C_LOC(SP_AGGLOMERATING_TMP(1))

  CALL FILL_AGGL_CONFIG(NA)
  mp%N_PARTICLE_BINS         = C_LOC(N_PARTICLE_BINS_TMP(1))
  mp%AGGLOMERATION_SPEC_INDEX= C_LOC(AGGLOMERATION_SPEC_INDEX_TMP(1))
  mp%AGGLOMERATION_SMIX_INDEX= C_LOC(AGGLOMERATION_SMIX_INDEX_TMP(1))
  mp%MIN_PARTICLE_DIAMETER   = C_LOC(MIN_PARTICLE_DIAMETER_TMP(1))
  mp%MAX_PARTICLE_DIAMETER   = C_LOC(MAX_PARTICLE_DIAMETER_TMP(1))

  NW = N_EXTERNAL_WALL_CELLS + N_INTERNAL_WALL_CELLS
  CALL ENSURE_WALL(NW)
  DO IW = 1, NW
    WC => WALL(IW)
    BC => BOUNDARY_COORD(WC%BC_INDEX)
    B1 => BOUNDARY_PROP1(WC%B1_INDEX)
    WALL_BC_TYPE_TMP(IW)  = WC%BOUNDARY_TYPE
    WALL_BC_INDEX_TMP(IW) = WC%BC_INDEX
    WALL_B1_INDEX_TMP(IW) = WC%B1_INDEX
    BC_IIG_TMP(IW) = BC%IIG; BC_JJG_TMP(IW) = BC%JJG
    BC_KKG_TMP(IW) = BC%KKG; BC_IOR_TMP(IW) = BC%IOR
    BP1_AREA_TMP(IW)   = B1%AREA
    BP1_TMP_F_TMP(IW)  = B1%TMP_F
    BP1_RHO_G_TMP(IW)  = B1%RHO_G
    BP1_TMP_G_TMP(IW)  = B1%TMP_G
  ENDDO
  mp%WALL_BC_TYPE      = C_LOC(WALL_BC_TYPE_TMP(1))
  mp%WALL_BC_INDEX     = C_LOC(WALL_BC_INDEX_TMP(1))
  mp%WALL_B1_INDEX     = C_LOC(WALL_B1_INDEX_TMP(1))
  mp%BC_IIG            = C_LOC(BC_IIG_TMP(1))
  mp%BC_JJG            = C_LOC(BC_JJG_TMP(1))
  mp%BC_KKG            = C_LOC(BC_KKG_TMP(1))
  mp%BC_IOR            = C_LOC(BC_IOR_TMP(1))
  mp%BP1_AREA          = C_LOC(BP1_AREA_TMP(1))
  mp%BP1_TMP_F         = C_LOC(BP1_TMP_F_TMP(1))
  mp%BP1_RHO_G         = C_LOC(BP1_RHO_G_TMP(1))
  mp%BP1_TMP_G         = C_LOC(BP1_TMP_G_TMP(1))


  IF (ALLOCATED(BP1_AWM_AEROSOL_FLAT)) DEALLOCATE(BP1_AWM_AEROSOL_FLAT)
  IF (N_SURFACE_DENSITY_SPECIES > 0 .AND. NW > 0) THEN
    ALLOCATE(BP1_AWM_AEROSOL_FLAT(NW * N_SURFACE_DENSITY_SPECIES))
    DO IW = 1, NW
      WC => WALL(IW)
      B1 => BOUNDARY_PROP1(WC%B1_INDEX)
      BP1_AWM_AEROSOL_FLAT((IW-1)*N_SURFACE_DENSITY_SPECIES+1 : IW*N_SURFACE_DENSITY_SPECIES) = &
        B1%AWM_AEROSOL(1:N_SURFACE_DENSITY_SPECIES)
    ENDDO
    mp%BP1_AWM_AEROSOL = C_LOC(BP1_AWM_AEROSOL_FLAT(1))
  ELSE
    mp%BP1_AWM_AEROSOL = C_NULL_PTR
  ENDIF


  IF (ALLOCATED(BP1_ZZ_G_FLAT)) DEALLOCATE(BP1_ZZ_G_FLAT)
  IF (NTS > 0 .AND. NW > 0) THEN
    ALLOCATE(BP1_ZZ_G_FLAT(NW * NTS))
    DO IW = 1, NW
      WC => WALL(IW)
      B1 => BOUNDARY_PROP1(WC%B1_INDEX)
      BP1_ZZ_G_FLAT((IW-1)*NTS+1 : IW*NTS) = B1%ZZ_G(1:NTS)
    ENDDO
    mp%BP1_ZZ_G = C_LOC(BP1_ZZ_G_FLAT(1))
  ELSE
    mp%BP1_ZZ_G = C_NULL_PTR
  ENDIF

  NICF = N_INTERNAL_CFACE_CELLS
  CALL ENSURE_CFACE(NICF)
  DO IW = 1, NICF
    CFA => CFACE(INTERNAL_CFACE_CELLS_LB + IW)
    CFACE_BC_TYPE_TMP(IW)  = CFA%BOUNDARY_TYPE
    CFACE_B1_INDEX_TMP(IW) = CFA%B1_INDEX
    CFACE_BC_INDEX_TMP(IW) = CFA%BC_INDEX
    CFACE_RSUM_G_TMP(IW)   = CFA%RSUM_G
  ENDDO
  mp%CFACE_BC_TYPE  = C_LOC(CFACE_BC_TYPE_TMP(1))
  mp%CFACE_B1_INDEX = C_LOC(CFACE_B1_INDEX_TMP(1))
  mp%CFACE_BC_INDEX = C_LOC(CFACE_BC_INDEX_TMP(1))
  mp%CFACE_RSUM_G   = C_LOC(CFACE_RSUM_G_TMP(1))

  NC = (IBAR+1)*(JBAR+1)*(KBAR+1)
  CALL ENSURE_CELL(NC)
  CELL_SOLID_TMP(:) = 0.0_EB
  DO K = 0, KBAR
    DO J = 0, JBAR
      DO I = 0, IBAR
        IC = CELL_INDEX(I, J, K)
        IF (IC > 0) THEN
          CELL_SOLID_TMP(IC) = MERGE(1.0_EB, 0.0_EB, CELL(IC)%SOLID)
        ENDIF
      ENDDO
    ENDDO
  ENDDO

  mp%WORK7 = C_LOC(WORK7(LBOUND(WORK7,1),LBOUND(WORK7,2),LBOUND(WORK7,3)))
  mp%WORK8 = C_LOC(WORK8(LBOUND(WORK8,1),LBOUND(WORK8,2),LBOUND(WORK8,3)))
  mp%WORK9 = C_LOC(WORK9(LBOUND(WORK9,1),LBOUND(WORK9,2),LBOUND(WORK9,3)))

  mp%LP_U = C_NULL_PTR; mp%LP_V = C_NULL_PTR; mp%LP_W = C_NULL_PTR
  mp%LP_RADIUS = C_NULL_PTR; mp%LP_RVC = C_NULL_PTR; mp%LP_PWT = C_NULL_PTR
  mp%LP_BC_INDEX = C_NULL_PTR; mp%LP_B1_INDEX = C_NULL_PTR
  mp%LP_U_VAL = 0.0_C_DOUBLE; mp%LP_V_VAL = 0.0_C_DOUBLE; mp%LP_W_VAL = 0.0_C_DOUBLE
  mp%LP_RADIUS_VAL = 0.0_C_DOUBLE; mp%LP_RVC_VAL = 0.0_C_DOUBLE; mp%LP_PWT_VAL = 0.0_C_DOUBLE
  mp%LP_BC_INDEX_VAL = 0; mp%LP_B1_INDEX_VAL = 0
  mp%LP_IIG_VAL = 0; mp%LP_JJG_VAL = 0; mp%LP_KKG_VAL = 0
  mp%LP_BP1_AREA_VAL = 0.0_C_DOUBLE; mp%LP_BP1_TMP_F_VAL = 0.0_C_DOUBLE
  mp%LP_BP1_RHO_G_VAL = 0.0_C_DOUBLE; mp%LP_BP1_TMP_G_VAL = 0.0_C_DOUBLE

  IF (ALLOCATED(D_Z_FLAT)) DEALLOCATE(D_Z_FLAT)
  IF (I_MAX_TEMP > 0 .AND. N_TRACKED_SPECIES > 0) THEN
    ALLOCATE(D_Z_FLAT((I_MAX_TEMP+1) * N_TRACKED_SPECIES))
    D_Z_FLAT(1:) = PACK(D_Z(0:I_MAX_TEMP, 1:N_TRACKED_SPECIES), .TRUE.)
    mp%D_Z_PTR = C_LOC(D_Z_FLAT(1))
  ELSE
    mp%D_Z_PTR = C_NULL_PTR
  ENDIF

  ARRAYS_ALLOCATED = .TRUE.
END SUBROUTINE PACK_MP_C


