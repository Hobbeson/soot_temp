SUBROUTINE FILL_SM_ARRAYS(NTS)
  INTEGER, INTENT(IN) :: NTS
  INTEGER :: I
  CALL ENSURE_SM(NTS)
  DO I = 1, NTS
    SM_DEPOSITING_TMP(I)          = MERGE(1.0_EB, 0.0_EB, SPECIES_MIXTURE(I)%DEPOSITING)
    SM_MEAN_DIAMETER_TMP(I)       = SPECIES_MIXTURE(I)%MEAN_DIAMETER
    SM_DENSITY_SOLID_TMP(I)       = SPECIES_MIXTURE(I)%DENSITY_SOLID
    SM_THERMOPHORETIC_DIAMETER_TMP(I) = SPECIES_MIXTURE(I)%THERMOPHORETIC_DIAMETER
    SM_CONDUCTIVITY_SOLID_TMP(I)  = SPECIES_MIXTURE(I)%CONDUCTIVITY_SOLID
    SM_H_F_TMP(I)                 = SPECIES_MIXTURE(I)%H_F
    SM_RCON_TMP(I)                = SPECIES_MIXTURE(I)%RCON
    SM_MW_TMP(I)                  = SPECIES_MIXTURE(I)%MW
    SM_AWM_INDEX_TMP(I)           = SPECIES_MIXTURE(I)%AWM_INDEX
    SM_AGGLOMERATION_INDEX_TMP(I) = SPECIES_MIXTURE(I)%AGGLOMERATION_INDEX
  ENDDO
END SUBROUTINE FILL_SM_ARRAYS

SUBROUTINE FILL_SP_ARRAYS(NSPEC)
  INTEGER, INTENT(IN) :: NSPEC
  INTEGER :: I
  CALL ENSURE_SP(NSPEC)
  DO I = 1, NSPEC
    SP_DENSITY_SOLID_TMP(I)     = SPECIES(I)%DENSITY_SOLID
    SP_CONDUCTIVITY_SOLID_TMP(I)= SPECIES(I)%CONDUCTIVITY_SOLID
    SP_AWM_INDEX_TMP(I)         = SPECIES(I)%AWM_INDEX
    SP_AGGLOMERATING_TMP(I)     = MERGE(1.0_EB, 0.0_EB, SPECIES(I)%AGGLOMERATING)
  ENDDO
END SUBROUTINE FILL_SP_ARRAYS

SUBROUTINE FILL_AGGL_CONFIG(NA)
  INTEGER, INTENT(IN) :: NA
  INTEGER :: I
  CALL ENSURE_AGGL_CONFIG(NA)
  DO I = 1, NA
    N_PARTICLE_BINS_TMP(I)         = N_PARTICLE_BINS(I)
    AGGLOMERATION_SPEC_INDEX_TMP(I)= AGGLOMERATION_SPEC_INDEX(I)
    AGGLOMERATION_SMIX_INDEX_TMP(I)= AGGLOMERATION_SMIX_INDEX(I)
    MIN_PARTICLE_DIAMETER_TMP(I)   = MIN_PARTICLE_DIAMETER(I)
    MAX_PARTICLE_DIAMETER_TMP(I)   = MAX_PARTICLE_DIAMETER(I)
  ENDDO
END SUBROUTINE FILL_AGGL_CONFIG


