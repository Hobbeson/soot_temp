SUBROUTINE ENSURE_SM(NTS)
  INTEGER, INTENT(IN) :: NTS
  IF (ARRAYS_ALLOCATED .AND. NTS == PREV_NTS) RETURN
  IF (ALLOCATED(SM_DEPOSITING_TMP)) DEALLOCATE(SM_DEPOSITING_TMP,SM_MEAN_DIAMETER_TMP,&
    SM_DENSITY_SOLID_TMP,SM_THERMOPHORETIC_DIAMETER_TMP,SM_CONDUCTIVITY_SOLID_TMP,&
    SM_H_F_TMP,SM_RCON_TMP,SM_MW_TMP,SM_AWM_INDEX_TMP,SM_AGGLOMERATION_INDEX_TMP)
  ALLOCATE(SM_DEPOSITING_TMP(NTS),SM_MEAN_DIAMETER_TMP(NTS),SM_DENSITY_SOLID_TMP(NTS),&
    SM_THERMOPHORETIC_DIAMETER_TMP(NTS),SM_CONDUCTIVITY_SOLID_TMP(NTS),&
    SM_H_F_TMP(NTS),SM_RCON_TMP(NTS),SM_MW_TMP(NTS),&
    SM_AWM_INDEX_TMP(NTS),SM_AGGLOMERATION_INDEX_TMP(NTS))
  PREV_NTS = NTS
END SUBROUTINE ENSURE_SM

SUBROUTINE ENSURE_SP(NSPEC)
  INTEGER, INTENT(IN) :: NSPEC
  IF (ARRAYS_ALLOCATED .AND. NSPEC == PREV_NSPEC) RETURN
  IF (ALLOCATED(SP_DENSITY_SOLID_TMP)) DEALLOCATE(SP_DENSITY_SOLID_TMP,SP_CONDUCTIVITY_SOLID_TMP,&
    SP_AWM_INDEX_TMP,SP_AGGLOMERATING_TMP)
  ALLOCATE(SP_DENSITY_SOLID_TMP(NSPEC),SP_CONDUCTIVITY_SOLID_TMP(NSPEC),&
    SP_AWM_INDEX_TMP(NSPEC),SP_AGGLOMERATING_TMP(NSPEC))
  PREV_NSPEC = NSPEC
END SUBROUTINE ENSURE_SP

